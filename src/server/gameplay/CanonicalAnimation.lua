local function prepare(clip)
    local frames,events={},{}
    local pointer,advance=1,0
    while pointer<=#clip.bytes do
        local byte=clip.bytes[pointer]
        if byte==0 then break end
        if byte<0xE0 then frames[#frames+1]=byte;advance+=1;pointer+=1
        else
            local count=OPCODES[byte][2]
            local params={}
            for i=1,count do params[i]=clip.bytes[pointer+i] end
            events[#events+1]=event(byte,params,pointer-1+(clip.byteOffset or 0),advance)
            pointer+=count+1
        end
    end
    assert(pointer==#clip.bytes and clip.bytes[pointer]==0,'Source clip must end at its decoded terminator')
    clip.frames=freeze(frames);clip.events=freeze(events)
    clip.description=freeze({animationId=clip.id,label=clip.label,displayAdvances=#frames,
        sourceLine=clip.line,sourceEndLine=clip.endLine,sourceFile='data/anims_moves.asm',
        fallsThroughDeclaredBlock=clip.fallthrough==true,branch=clip.branch or 'Normal',
        frameInterpretation='Caller postprocessing may transform these source frame values'})
    freeze(clip.bytes)
    return clip
end
