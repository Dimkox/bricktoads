local function rawByte(value) return integer(value) and value>= -128 and value<=255 end
function Animation.heroFrame(state,input)
    input=inputRow(input)
    if not input then return nil,'INVALID_STATE_INPUT' end
    if state=='Idle' then return input.blink==true and 2 or 1 end
    if state=='CarryIdle' then return 0x11 end
    if HERO[state] then
        local index=phaseIndex(input,#HERO[state])
        if not index then return nil,'INVALID_STATE_INPUT' end
        return HERO[state][index]
    end
    if state=='Air' then
        if input.holding==true then return 0x2E end
        if not rawByte(input.zSpeedRaw) then return nil,'INVALID_STATE_INPUT' end
        return (input.zSpeedRaw+2)%256<5 and 0x2D or 5
    end
    return nil,'UNKNOWN_STATE'
end
function Animation.dragonFrame(state,input)
    input=inputRow(input)
    if not input then return nil,'INVALID_STATE_INPUT' end
    if state=='Disabled' then return 0xA end
    if state=='Attack' or state=='Capture' then return 0xB end
    if state=='LightReaction' then
        if not integer(input.timerRaw) or input.timerRaw<0 or input.timerRaw>255 then return nil,'INVALID_STATE_INPUT' end
        if input.timerRaw>=0x26 then return 0xC end
    elseif state~='Locomotion' then return nil,'UNKNOWN_STATE' end
    local index=phaseIndex(input,4)
    if not index then return nil,'INVALID_STATE_INPUT' end
    if input.zSpeedRaw~=nil and not rawByte(input.zSpeedRaw) then return nil,'INVALID_STATE_INPUT' end
    if state=='Locomotion' and input.approaching==true and input.zSpeedRaw~=nil and input.zSpeedRaw%256~=0 then return 9 end
    return DRAGON[index]
end

