-- Models the byte interpreter and its caller clock only. Commands are markers:
-- contact, speed, linkage and successful-hit pointer changes never execute here.
-- Dash's verified alternate continuation is selected explicitly.
local schedules={}
local function schedule(clip,mask,phase,firstRead)
    local key=clip.id..':'..clip.description.branch..':'..mask..':'..phase..':'..firstRead
    if schedules[key] then return schedules[key] end
    local result={rows={}}
    local pointer=1
    for tick=0,MAX_CALLS do
        if (tick>0 or firstRead=='Advance') and (phase+tick)%(mask+1)==0 then pointer+=1 end
        local events={}
        while true do
            local byte=clip.bytes[pointer]
            if byte==nil then result.error='SOURCE_BOUNDS';result.endTick=tick;break end
            if byte==0 then
                result.endTick=tick
                result.rows[tick+1]=freeze({animationId=clip.id,branch=clip.description.branch,ended=true,
                    sourceByte=pointer-1+(clip.byteOffset or 0),events=events})
                break
            end
            if byte<0xE0 then
                result.rows[tick+1]=freeze({animationId=clip.id,branch=clip.description.branch,frameId=byte,ended=false,
                    sourceByte=pointer-1+(clip.byteOffset or 0),events=events})
                break
            end
            local opcode=OPCODES[byte]
            if not opcode then result.error='UNKNOWN_OPCODE';result.endTick=tick;break end
            local params={}
            for i=1,opcode[2] do
                params[i]=clip.bytes[pointer+i]
                if params[i]==nil then result.error='SOURCE_BOUNDS' end
            end
            if result.error then result.endTick=tick;break end
            events[#events+1]=event(byte,params,pointer-1+(clip.byteOffset or 0),nil)
            pointer+=opcode[2]+1
        end
        if result.endTick then break end
    end
    assert(result.endTick,'Finite source clip exceeded the explicit clock bound')
    schedules[key]=result
    return result
end
function Animation.sampleClock(id,clock)
    local clip,code=selected(id,clock)
    if not clip then return nil,code end
    if type(clock)~='table' then return nil,'INVALID_CLOCK' end
    local calls,mask,phase=clock.elapsedCalls,clock.callerMask,clock.firstFrameCounterPhase
    local firstRead=clock.firstRead or (clock.branch=='DashLowLifeTail' and 'Read' or 'Advance')
    if not integer(calls) or calls<0 or calls>MAX_CALLS or (mask~=0 and mask~=1 and mask~=3)
        or not integer(phase) or phase<0 or phase>mask or (firstRead~='Read' and firstRead~='Advance')
        or (clock.branch=='DashLowLifeTail' and firstRead~='Read') then return nil,'INVALID_CLOCK' end
    local timeline=schedule(clip,mask,phase,firstRead)
    if calls>=timeline.endTick and timeline.error then return nil,timeline.error end
    local sample=timeline.rows[math.min(calls,timeline.endTick)+1]
    -- End-command markers belong to the termination call, not every later sample.
    if calls>timeline.endTick then return freeze({animationId=id,branch=clip.description.branch,ended=true,
        sourceByte=sample.sourceByte,events=EMPTY,endedAtCall=timeline.endTick}) end
    return sample
end
