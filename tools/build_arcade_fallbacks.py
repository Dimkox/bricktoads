"""Bake indexed portraits from the original artwork for clients with a cold image cache."""
from base64 import b64encode
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[1]
ART = ROOT / "assets/interface/arcade"
SIZE = 96
SHEETS = (("heroes-and-rivals-atlas", "ArcadePixels"), ("campaign-enemies-atlas", "ArcadeEnemyPixels"))


def encode(data):
    return '"' + b64encode(data).decode("ascii") + '"'


def main():
    width = 4 * SIZE
    for asset, module in SHEETS:
        filters = (f"scale={width}:{width}:flags=lanczos,split[a][b];"
                   "[a]palettegen=reserve_transparent=0[p];[b][p]paletteuse=dither=none")
        data = subprocess.check_output([
            "ffmpeg", "-v", "error", "-i", str(ART / (asset + ".png")), "-filter_complex", filters,
            "-frames:v", "1", "-f", "rawvideo", "-pix_fmt", "pal8", "pipe:1",
        ])
        assert len(data) == width * width + 1024
        bgra = data[-1024:]
        rgb = b"".join(bytes((bgra[i+2], bgra[i+1], bgra[i])) for i in range(0, 1024, 4))
        lines = ["-- Generated by tools/build_arcade_fallbacks.py.", "return {",
                 f"    size = {SIZE},", "    palette = " + encode(rgb) + ","]
        for index in range(16):
            x, y = index % 4 * SIZE, index // 4 * SIZE
            tile = b"".join(data[row * width + x:row * width + x + SIZE] for row in range(y, y + SIZE))
            lines.append("    " + encode(tile) + ",")
        (ROOT / f"src/shared/{module}.luau").write_text("\n".join(lines + ["}", ""]), encoding="ascii")


if __name__ == "__main__":
    main()
