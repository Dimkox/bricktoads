"""Bake low-resolution menu artwork for clients waiting on Roblox image delivery."""
from base64 import b64encode
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[1]
ART = ROOT / "assets/interface/arcade"
SHEETS = ("heroes-and-rivals-atlas", "campaign-enemies-atlas")


def pixels(name, width, height):
    return subprocess.check_output([
        "ffmpeg", "-v", "error", "-i", str(ART / (name + ".png")),
        "-vf", f"scale={width}:{height}:flags=area", "-frames:v", "1",
        "-f", "rawvideo", "-pix_fmt", "rgb24", "pipe:1",
    ])


def encode(rgb):
    return '"' + b64encode(rgb).decode("ascii") + '"'


def main():
    lines = ["-- Generated by tools/build_arcade_fallbacks.py from the original menu artwork.",
             "return {", "    splash = " + encode(pixels("flooded-causeway-splash", 64, 40)) + ","]
    for sheet in SHEETS:
        data = pixels(sheet, 128, 128)
        for index in range(16):
            x, y = index % 4 * 32, index // 4 * 32
            tile = b"".join(data[(row * 128 + x) * 3:(row * 128 + x + 32) * 3]
                            for row in range(y, y + 32))
            lines.append("    " + encode(tile) + ",")
    (ROOT / "src/shared/ArcadePixels.luau").write_text("\n".join(lines + ["}", ""]), encoding="ascii")


if __name__ == "__main__":
    main()
