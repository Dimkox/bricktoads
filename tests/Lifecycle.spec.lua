-- The same behavior suite runs in the portable harness and the Studio test place.
return function(Core)
    assert(type(Core.new) == "function", "RunLifecycle.new must be implemented")
    assert(type(Core.apply) == "function", "RunLifecycle.apply must be implemented")
    local passed, failed, serial = 0, 0, 0
    local function eq(actual, expected)
        assert(actual == expected, "expected " .. tostring(expected) .. ", got " .. tostring(actual))
    end
    local function test(name, body)
        local ok, message = pcall(body)
        if ok then passed = passed + 1; print("PASS " .. name)
        else failed = failed + 1; print("FAIL " .. name .. ": " .. tostring(message)) end
    end
    local function new(count, id)
        local roster = {}
        for i = 1, count or 1 do roster[i] = { userId = i, template = "Mr. Green" } end
        return Core.new(id or "run-a", "group-a", roster, "level-1")
    end
    local function event(s, kind, fields)
        serial = serial + 1
        local e = {id = "event-" .. serial, runId = s.runId, expectedRevision = s.revision, kind = kind, now = s.time}
        for k, v in pairs(fields or {}) do e[k] = v end
        return e
    end
    local function send(s, kind, fields, code)
        local nextState, result, ack = Core.apply(s, event(s, kind, fields))
        eq(result, code or "OK")
        return nextState, ack
    end
    local function identity(s, userId, fields)
        local h = s.heroes[userId]
        local f = {userId = userId, actorId = h.actorId, attempt = h.attempt, levelEpoch = s.levelEpoch}
        for k, v in pairs(fields or {}) do f[k] = v end
        return f
    end
    local function spawn(s, userId, safe, now)
        local h = s.heroes[userId]
        s = send(s, "ReserveSpawn", {userId = userId, connectionEpoch = h.connectionEpoch, now = now or s.time})
        serial = serial + 1
        return send(s, "CommitSpawn", {userId = userId, token = s.heroes[userId].pending.token, actorId = "actor-" .. serial, safe = safe ~= false, now = now or s.time})
    end
    local function alive(count)
        local s = new(count)
        for i = 1, count or 1 do s = spawn(s, i) end
        return s
    end
    local function die(s, userId)
        return send(s, "Death", identity(s, userId))
    end
    local function connect(s, userId, connected)
        return send(s, "Connection", {userId = userId, connectionEpoch = s.heroes[userId].connectionEpoch, connected = connected})
    end
    local function eliminate(s, userId)
        for _ = 1, 3 do s = die(s, userId); s = spawn(s, userId) end
        return die(s, userId)
    end
    local function transition(s, userId, target)
        local f = identity(s, userId, {levelId = target, destinationSafe = true, prerequisitesMet = true})
        return send(s, "AdvanceLevel", f)
    end

    test("1/2/3 heroes share templates, not resources", function()
        for count = 1, 3 do
            local s = alive(count)
            for i = 1, count do
                eq(s.heroes[i].health, 5); eq(s.heroes[i].respawns, 3)
                eq(s.heroes[i].attempt, 1); eq(s.heroes[i].shield, nil)
            end
            s = die(s, 1); s = spawn(s, 1)
            eq(s.heroes[1].respawns, 2)
            for i = 2, count do eq(s.heroes[i].respawns, 3) end
        end
    end)
    test("invalid roster rejected", function()
        eq(pcall(function() new(0) end), false)
        eq(pcall(function() new(4) end), false)
        eq(pcall(function() Core.new("r", "g", {{userId=1,template="Mr. Green"},{userId=1,template="Mr. Brown"}}, "l") end), false)
        eq(pcall(function() Core.new("r", "g", {{userId=-1,template="Mr. Green"}}, "l") end), false)
        eq(pcall(function() Core.new("r", "g", {{userId=1,template="unknown"}}, "l") end), false)
    end)
    test("late hero is never added", function()
        local s = alive()
        local n = send(s, "ReserveSpawn", {userId=2,connectionEpoch=1}, "UNKNOWN_HERO")
        eq(n, s); eq(n.heroes[2], nil)
    end)
    test("initial failure does not spend a respawn", function()
        local s = new(); s = send(s, "ReserveSpawn", {userId=1,connectionEpoch=1})
        s = send(s, "AbortSpawn", {userId=1,token=s.heroes[1].pending.token})
        eq(s.heroes[1].respawns, 3); eq(s.heroes[1].attempt, 0)
        s = spawn(s, 1); eq(s.heroes[1].respawns, 3)
    end)
    test("unsafe initial spawn is not an invented free emergency life", function()
        local s = new(); s = send(s, "ReserveSpawn", {userId=1,connectionEpoch=1})
        s = send(s, "CommitSpawn", {userId=1,token=s.heroes[1].pending.token,actorId="a",safe=false}, "UNSAFE_INITIAL_SPAWN")
        eq(s.heroes[1].attempt, 0); eq(s.heroes[1].respawns, 3)
    end)
    test("failed respawn consumes nothing", function()
        local s = die(alive(), 1); s = send(s, "ReserveSpawn", {userId=1,connectionEpoch=1})
        s = send(s, "AbortSpawn", {userId=1,token=s.heroes[1].pending.token})
        eq(s.heroes[1].respawns, 3); eq(s.heroes[1].status, "AwaitingRespawn")
    end)
    test("three successful respawns then actual death at zero", function()
        local s = alive()
        for left = 2, 0, -1 do s = die(s, 1); s = spawn(s, 1); eq(s.heroes[1].respawns, left) end
        eq(s.heroes[1].status, "Alive"); eq(s.status, "Active")
        s = die(s, 1); eq(s.heroes[1].status, "Eliminated"); eq(s.status, "Lost")
        eq(s.partyDissolved, true); eq(s.heroes[1].view, "Menu")
        send(s, "ReserveSpawn", {userId=1,connectionEpoch=1}, "RUN_CLOSED")
    end)
    test("normal shield is exactly two seconds", function()
        local s = spawn(die(alive(), 1), 1, true, 10)
        eq(s.heroes[1].shield.deadline, 12)
        send(s, "SetHealth", identity(s, 1, {health=4,now=11.999}), "PROTECTED")
        s = send(s, "SetHealth", identity(s, 1, {health=4,now=12})); eq(s.heroes[1].health, 4)
    end)
    test("accepted attack cancels protection even without a hit", function()
        local s = spawn(die(alive(), 1), 1, true)
        s = send(s, "BeginAttack", identity(s, 1, {connectionEpoch=1}))
        eq(s.heroes[1].shield, nil)
        s = send(s, "SetHealth", identity(s, 1, {health=4})); eq(s.heroes[1].health, 4)
    end)
    test("zero normalized health alone is not a death event", function()
        local s = alive(); s = send(s, "SetHealth", identity(s, 1, {health=0}))
        eq(s.heroes[1].status, "Alive"); eq(s.heroes[1].respawns, 3)
    end)
    test("emergency appearance costs one and expires at ten seconds", function()
        local s = spawn(die(alive(), 1), 1, false, 5)
        eq(s.heroes[1].respawns, 2); eq(s.heroes[1].shield.kind, "Emergency")
        eq(s.heroes[1].shield.deadline, 15)
        send(s, "ExpireShield", identity(s, 1, {now=14.999}), "NOT_DUE")
    end)
    test("emergency cycles consume appearances without deaths", function()
        local s = spawn(die(alive(), 1), 1, false)
        for at = 10, 20, 10 do
            s = send(s, "ExpireShield", identity(s, 1, {now=at}))
            eq(s.heroes[1].retryReady, true); s = spawn(s, 1, false, at)
        end
        eq(s.heroes[1].attempt, 4); eq(s.heroes[1].respawns, 0)
        s = send(s, "ExpireShield", identity(s, 1, {now=30}))
        eq(s.heroes[1].retryReady, false); eq(s.heroes[1].shield, nil)
        eq(s.heroes[1].status, "Alive"); eq(s.status, "Active")
        send(s, "ReserveSpawn", {userId=1,connectionEpoch=1}, "SPAWN_NOT_ALLOWED")
    end)
    test("safe relocation does not heal or spend again", function()
        local s = spawn(die(alive(), 1), 1, false)
        s = send(s, "SetHealth", identity(s, 1, {health=2,now=10}))
        local a = s.heroes[1].actorId
        s = send(s, "RelocateToSafety", identity(s, 1, {safe=true,now=10}))
        eq(s.heroes[1].health, 2); eq(s.heroes[1].respawns, 2)
        eq(s.heroes[1].actorId, a); eq(s.heroes[1].shield, nil)
        send(s, "ExpireShield", identity(s, 1, {now=10}), "NO_SHIELD")
    end)
    test("emergency attack cancels hold and the later retry", function()
        local s = spawn(die(alive(), 1), 1, false)
        s = send(s, "BeginAttack", identity(s, 1, {connectionEpoch=1}))
        eq(s.heroes[1].retryReady, false); eq(s.heroes[1].shield, nil)
        send(s, "ExpireShield", identity(s, 1, {now=10}), "NO_SHIELD")
    end)
    test("failed emergency replacement leaves existing living attempt", function()
        local s = spawn(die(alive(), 1), 1, false)
        s = send(s, "ExpireShield", identity(s, 1, {now=10}))
        local actor = s.heroes[1].actorId
        s = send(s, "ReserveSpawn", {userId=1,connectionEpoch=1})
        s = send(s, "AbortSpawn", {userId=1,token=s.heroes[1].pending.token})
        eq(s.heroes[1].actorId, actor); eq(s.heroes[1].status, "Alive")
        eq(s.heroes[1].respawns, 2); eq(s.heroes[1].shield, nil)
    end)
    test("offline emergency expiry never spawns or kills", function()
        local s = spawn(die(alive(), 1), 1, false); s = connect(s, 1, false)
        s = send(s, "ExpireShield", identity(s, 1, {now=10}))
        eq(s.heroes[1].retryReady, false); eq(s.heroes[1].respawns, 2)
        eq(s.heroes[1].status, "Alive"); s = connect(s, 1, true)
        send(s, "ReserveSpawn", {userId=1,connectionEpoch=s.heroes[1].connectionEpoch}, "SPAWN_NOT_ALLOWED")
    end)
    test("offline dead hero waits for owner without spending", function()
        local s = connect(alive(), 1, false); s = die(s, 1)
        eq(s.status, "Active"); eq(s.heroes[1].status, "AwaitingRespawn")
        send(s, "ReserveSpawn", {userId=1,connectionEpoch=s.heroes[1].connectionEpoch}, "OFFLINE")
        s = connect(s, 1, true); s = spawn(s, 1); eq(s.heroes[1].respawns, 2)
    end)
    test("rejoin living actor preserves health, resources and deadline", function()
        local s = spawn(die(alive(), 1), 1, true, 10)
        local actor, deadline = s.heroes[1].actorId, s.heroes[1].shield.deadline
        s = connect(s, 1, false); s = connect(s, 1, true)
        eq(s.heroes[1].actorId, actor); eq(s.heroes[1].respawns, 2); eq(s.heroes[1].shield.deadline, deadline)
    end)
    test("offline actor still accepts damage and death", function()
        local s = connect(alive(), 1, false)
        s = send(s, "SetHealth", identity(s, 1, {health=1})); eq(s.heroes[1].health, 1)
        s = die(s, 1); eq(s.heroes[1].status, "AwaitingRespawn")
    end)
    test("offline owner cannot start attacks", function()
        local s = connect(alive(), 1, false)
        send(s, "BeginAttack", identity(s, 1, {connectionEpoch=s.heroes[1].connectionEpoch}), "OFFLINE")
    end)
    test("stale connection cannot command after rejoin", function()
        local s = alive(); local epoch = s.heroes[1].connectionEpoch
        s = connect(s, 1, false); s = connect(s, 1, true)
        send(s, "BeginAttack", identity(s, 1, {connectionEpoch=epoch}), "STALE_CONNECTION")
    end)
    test("disconnect invalidates an uncommitted spawn", function()
        local s = die(alive(), 1); s = send(s, "ReserveSpawn", {userId=1,connectionEpoch=1})
        local token = s.heroes[1].pending.token
        s = connect(s, 1, false); s = connect(s, 1, true)
        send(s, "CommitSpawn", {userId=1,token=token,actorId="late",safe=true}, "STALE_RESERVATION")
        eq(s.heroes[1].respawns, 3)
    end)
    test("duplicate commit replays the established acknowledgement", function()
        local s = die(alive(), 1); s = send(s, "ReserveSpawn", {userId=1,connectionEpoch=1})
        local e = event(s, "CommitSpawn", {userId=1,token=s.heroes[1].pending.token,actorId="once",safe=true})
        local n, code, ack = Core.apply(s, e); eq(code, "OK")
        local n2, replay, ack2 = Core.apply(n, e); eq(replay, "REPLAY"); eq(n2, n)
        eq(ack2.revision, ack.revision); eq(n2.heroes[1].respawns, 2)
        ack2.revision = -1
        local _, _, ack3 = Core.apply(n, e); eq(ack3.revision, ack.revision)
    end)
    test("same event id with different payload rejected", function()
        local s = alive(); local e = event(s, "SetHealth", identity(s, 1, {health=4}))
        s = Core.apply(s, e); e.health = 5
        local n, code = Core.apply(s, e); eq(code, "EVENT_ID_REUSED"); eq(n, s); eq(n.heroes[1].health, 4)
    end)
    test("concurrent requests cannot reserve twice", function()
        local s = die(alive(), 1)
        local a = event(s, "ReserveSpawn", {userId=1,connectionEpoch=1})
        local b = event(s, "ReserveSpawn", {userId=1,connectionEpoch=1})
        s = Core.apply(s, a); local n, code = Core.apply(s, b)
        eq(code, "STALE_REVISION"); eq(n, s)
        send(s, "ReserveSpawn", {userId=1,connectionEpoch=1}, "SPAWN_PENDING")
    end)
    test("old actor death cannot kill its replacement", function()
        local s = alive(); local old = identity(s, 1)
        s = die(s, 1); s = spawn(s, 1)
        send(s, "Death", old, "STALE_ACTOR"); eq(s.heroes[1].status, "Alive")
    end)
    test("actor ids cannot be reused within a run", function()
        local s = alive(); local old = s.heroes[1].actorId
        s = die(s, 1); s = send(s, "ReserveSpawn", {userId=1,connectionEpoch=1})
        send(s, "CommitSpawn", {userId=1,token=s.heroes[1].pending.token,actorId=old,safe=true}, "ACTOR_ID_REUSED")
    end)
    test("aborted token cannot confirm a later reservation", function()
        local s = new(); s = send(s, "ReserveSpawn", {userId=1,connectionEpoch=1})
        local token = s.heroes[1].pending.token
        s = send(s, "AbortSpawn", {userId=1,token=token})
        s = send(s, "ReserveSpawn", {userId=1,connectionEpoch=1})
        send(s, "CommitSpawn", {userId=1,token=token,actorId="late",safe=true}, "STALE_RESERVATION")
    end)
    test("level transition heals once without resetting resources", function()
        local s = spawn(die(alive(), 1), 1, true)
        s = send(s, "SetHealth", identity(s, 1, {health=1,now=2}))
        local attempt = s.heroes[1].attempt
        local e = event(s, "AdvanceLevel", identity(s, 1, {levelId="level-2",destinationSafe=true,prerequisitesMet=true}))
        s = Core.apply(s, e); eq(s.heroes[1].health, 5); eq(s.heroes[1].respawns, 2)
        eq(s.heroes[1].attempt, attempt)
        s = send(s, "SetHealth", identity(s, 1, {health=3}))
        local n, code = Core.apply(s, e); eq(code, "REPLAY"); eq(n.heroes[1].health, 3)
    end)
    test("one living hero completes an eligible exit", function()
        local s = alive(3); s = transition(s, 1, "level-2")
        eq(s.levelId, "level-2"); for i=1,3 do eq(s.heroes[i].attempt, 1) end
    end)
    test("exit prerequisites cannot be skipped", function()
        local s = alive()
        send(s, "AdvanceLevel", identity(s, 1, {levelId="level-2",destinationSafe=true,prerequisitesMet=false}), "EXIT_NOT_READY")
    end)
    test("eliminated member stays eliminated on next level", function()
        local s = eliminate(alive(2), 1); s = transition(s, 2, "level-2")
        eq(s.heroes[1].status, "Eliminated"); eq(s.heroes[1].respawns, 0)
        send(s, "ReserveSpawn", {userId=1,connectionEpoch=1}, "SPAWN_NOT_ALLOWED")
    end)
    test("pending offline respawn prevents false defeat", function()
        local s = alive(2); s = connect(s, 1, false); s = die(s, 1)
        s = eliminate(s, 2); eq(s.status, "Active")
        eq(s.heroes[1].status, "AwaitingRespawn"); eq(s.heroes[2].status, "Eliminated")
    end)
    test("old level reservations are invalidated; owner uses current level", function()
        local s = alive(2); s = die(s, 1)
        s = send(s, "ReserveSpawn", {userId=1,connectionEpoch=1}); local token = s.heroes[1].pending.token
        s = transition(s, 2, "level-2")
        send(s, "CommitSpawn", {userId=1,token=token,actorId="old-level",safe=true}, "STALE_RESERVATION")
        s = spawn(s, 1); eq(s.levelId, "level-2"); eq(s.heroes[1].respawns, 2)
    end)
    test("old level death is rejected even for the same actor", function()
        local s = alive(); local old = identity(s, 1)
        s = transition(s, 1, "level-2"); send(s, "Death", old, "STALE_LEVEL")
    end)
    test("transition preserves ordinary deadline and clears emergency hold", function()
        local s = alive(2); s = spawn(die(s, 1), 1, true, 5)
        s = spawn(die(s, 2), 2, false, 5)
        s = transition(s, 1, "level-2")
        eq(s.heroes[1].shield.deadline, 7); eq(s.heroes[2].shield, nil)
        eq(s.heroes[1].respawns, 2); eq(s.heroes[2].respawns, 2)
    end)
    test("spectator menu choice does not dissolve remaining party", function()
        local s = eliminate(alive(2), 1)
        s = send(s, "ChooseView", {userId=1,view="Menu",connectionEpoch=1})
        eq(s.status, "Active"); eq(s.partyDissolved, false)
        s = send(s, "ChooseView", {userId=1,view="Spectating",connectionEpoch=1})
        eq(s.heroes[1].status, "Eliminated"); eq(s.heroes[1].view, "Spectating")
        s = eliminate(s, 2); eq(s.status, "Lost"); eq(s.partyDissolved, true)
    end)
    test("new game gives a new independent roster and resources", function()
        local old = eliminate(alive(), 1); local fresh = new(1, "run-b")
        eq(old.status, "Lost"); eq(fresh.heroes[1].respawns, 3)
        eq(fresh.heroes[1].status, "AwaitingInitial")
    end)
    test("wrong run events cannot affect another game", function()
        local s = alive(); local e = event(s, "Death", identity(s, 1)); e.runId = "other"
        local n, code = Core.apply(s, e); eq(code, "WRONG_RUN"); eq(n, s)
    end)
    test("input snapshots remain immutable", function()
        local s = alive(); local n = send(s, "SetHealth", identity(s, 1, {health=2}))
        eq(s.heroes[1].health, 5); eq(n.heroes[1].health, 2)
        n.heroes[1].health = 1; eq(s.heroes[1].health, 5)
    end)
    test("malformed times, revisions and numeric health are rejected", function()
        local s = alive()
        for _, bad in ipairs({0/0, math.huge, -math.huge}) do
            send(s, "SetHealth", identity(s, 1, {health=bad}), "INVALID_EVENT")
        end
        send(s, "SetHealth", identity(s, 1, {health=6}), "INVALID_HEALTH")
        send(s, "SetHealth", identity(s, 1, {health=-1}), "INVALID_HEALTH")
        send(s, "SetHealth", identity(s, 1, {health=2,now=-1}), "INVALID_EVENT")
        send(s, "SetHealth", identity(s, 1, {health=2,expectedRevision=0.5}), "INVALID_EVENT")
        send(s, "SetHealth", identity(s, 1, {health=2,extra=true}), "UNKNOWN_FIELD")
        send(s, "SetHealth", identity(s, 1, {health="2"}), "INVALID_HEALTH")
    end)
    test("server clock cannot move backwards", function()
        local s = alive(); s = send(s, "SetHealth", identity(s, 1, {health=4,now=10}))
        send(s, "SetHealth", identity(s, 1, {health=3,now=9}), "TIME_REVERSED")
    end)
    test("safe relocation wins a serialized race without double spending", function()
        local s = spawn(die(alive(), 1), 1, false)
        local timeout = event(s, "ExpireShield", identity(s, 1, {now=10}))
        s = send(s, "RelocateToSafety", identity(s, 1, {safe=true,now=10}))
        local n, code = Core.apply(s, timeout); eq(code, "STALE_REVISION")
        eq(n.heroes[1].respawns, 2); eq(n.heroes[1].attempt, 2)
    end)
    test("death cancels a prepared emergency replacement", function()
        local s = spawn(die(alive(), 1), 1, false)
        s = send(s, "ExpireShield", identity(s, 1, {now=10}))
        s = send(s, "ReserveSpawn", {userId=1,connectionEpoch=1})
        local token = s.heroes[1].pending.token; s = die(s, 1)
        send(s, "CommitSpawn", {userId=1,token=token,actorId="late",safe=true}, "STALE_RESERVATION")
        eq(s.heroes[1].respawns, 2)
    end)
    test("attack cancels a prepared emergency replacement", function()
        local s = spawn(die(alive(), 1), 1, false)
        s = send(s, "ExpireShield", identity(s, 1, {now=10}))
        s = send(s, "ReserveSpawn", {userId=1,connectionEpoch=1})
        local token = s.heroes[1].pending.token
        s = send(s, "BeginAttack", identity(s, 1, {connectionEpoch=1}))
        send(s, "CommitSpawn", {userId=1,token=token,actorId="late",safe=true}, "STALE_RESERVATION")
    end)
    test("120 deterministic life-cycle sequences preserve invariants", function()
        for seed = 1, 120 do
            local count = seed % 3 + 1
            local s = alive(count)
            for userId = 1, count do
                for cycle = 1, 3 do
                    s = die(s, userId)
                    if (seed + cycle + userId) % 2 == 0 then
                        s = connect(s, userId, false); eq(s.status, "Active"); s = connect(s, userId, true)
                    end
                    s = spawn(s, userId, (seed + cycle) % 2 == 0)
                    for _, h in pairs(s.heroes) do
                        assert(h.respawns >= 0 and h.respawns <= 3)
                        assert(h.health >= 0 and h.health <= 5)
                        assert(h.attempt >= 1 and h.attempt <= 4)
                        if h.status == "Eliminated" then eq(h.respawns, 0) end
                    end
                    eq(s.heroes[userId].respawns, 3-cycle)
                end
                eq(s.heroes[userId].status, "Alive"); s = die(s, userId)
            end
            eq(s.status, "Lost"); eq(s.partyDissolved, true)
        end
    end)
    print(string.format("RESULT: %d passed; %d failed", passed, failed))
    assert(failed == 0, tostring(failed) .. " lifecycle tests failed")
    return passed
end
