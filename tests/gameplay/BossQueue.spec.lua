return function(BossQueue)
    local passed=0
    local function test(name,fn)
        fn(); passed+=1; print('PASS '..name)
    end
    local function eq(actual,expected,message)
        assert(actual==expected,(message or 'Unexpected result')..': expected '..tostring(expected)..', got '..tostring(actual))
    end
    local function queue(eligible)
        return BossQueue.new({inviteSeconds=10,connectSeconds=15},eligible or function() return true end)
    end
    local function offer(q,userId)
        local view=q:view(userId,0)
        eq(view.state,'Invited'); assert(type(view.offerId)=='string')
        return view.offerId
    end

    -- A duplicate selection moving an entry to the tail breaks this FIFO assertion.
    test('duplicate selection preserves FIFO priority and invitation deadline',function()
        local q=queue()
        eq(q:select(1,'Guardian',0),'OK'); eq(q:select(2,'Guardian',0),'OK')
        eq(q:select(1,'Guardian',1),'OK')
        eq(q:view(1,1).position,1); eq(q:view(2,1).position,2)
        eq(q:register('first','Guardian',{runId='a'},1),'OK')
        local invited=q:view(1,1)
        eq(invited.state,'Invited'); eq(invited.deadline,11)
        eq(q:select(1,'Guardian',5),'OK')
        eq(q:view(1,5).offerId,invited.offerId); eq(q:view(1,5).deadline,11)
        eq(q:view(2,5).state,'Queued'); eq(q:start('first',5).state,'Waiting')
    end)

    test('select fills a previously registered slot',function()
        local q=queue()
        q:register('first','Guardian',{},0)
        eq(q:select(1,'Guardian',2),'OK')
        eq(q:view(1,2).state,'Invited'); eq(q:view(1,2).deadline,12)
    end)

    -- Reoffering a rotated player in the same slot would keep this encounter waiting forever.
    test('decline rotates once and exhausted slot starts NPC',function()
        local q=queue()
        q:select(1,'Guardian',0); q:select(2,'Guardian',0); q:register('first','Guardian',{},0)
        eq(q:reply(1,offer(q,1),false,1),'OK')
        local second=q:view(2,1)
        eq(second.state,'Invited'); eq(q:view(1,1).position,2)
        eq(q:reply(2,second.offerId,false,2),'OK')
        eq(q:view(1,2).state,'Queued'); eq(q:view(1,2).position,1)
        eq(q:view(2,2).state,'Queued'); eq(q:view(2,2).position,2)
        eq(q:start('first',2).state,'NPC')
        q:register('future','Guardian',{},3)
        eq(q:view(1,3).slotId,'future')
    end)

    test('invitation accepts strictly before ten seconds and reserves a separate connection deadline',function()
        local q=queue()
        q:select(1,'Guardian',0); q:select(2,'Guardian',0); q:register('first','Guardian',{},0)
        local token=offer(q,1)
        eq(q:reply(1,token,true,9.5),'OK')
        local accepted=q:view(1,9.5)
        eq(accepted.state,'Accepted'); eq(accepted.deadline,24.5); eq(accepted.position,nil)
        eq(q:view(2,9.5).position,1); eq(q:start('first',10).state,'Waiting')
        eq(q:reply(1,token,true,11),'OK'); eq(q:view(1,11).deadline,24.5)
    end)

    test('invitation at exact expiry cannot accept and rotates to the next candidate',function()
        local q=queue()
        q:select(1,'Guardian',0); q:select(2,'Guardian',0); q:register('first','Guardian',{},0)
        local token=offer(q,1)
        eq(q:reply(1,token,true,10),'STALE_OFFER')
        eq(q:view(1,10).state,'Queued'); eq(q:view(1,10).position,2)
        eq(q:view(2,10).state,'Invited'); eq(q:view(2,10).deadline,20)
        q:step(20)
        eq(q:start('first',20).state,'NPC')
    end)

    test('connection strictly before its deadline becomes ready and starts one human',function()
        local q=queue()
        q:select(1,'Guardian',0); q:register('first','Guardian',{},0)
        local token=offer(q,1)
        q:reply(1,token,true,1)
        eq(q:start('first',15.999).state,'Waiting')
        eq(q:connect(1,token,15.999),'OK'); eq(q:view(1,15.999).state,'Ready')
        local started=q:start('first',16)
        eq(started.state,'Human'); eq(started.userId,1); eq(q:view(1,16).state,'Active')
        eq(q:start('first',100).userId,1); eq(q:connect(1,token,100),'OK')
    end)

    test('accepted reserve expires at connection deadline without rejoining the queue',function()
        local q=queue()
        q:select(1,'Guardian',0); q:select(2,'Guardian',0); q:register('first','Guardian',{},0)
        local token=offer(q,1); q:reply(1,token,true,1)
        eq(q:connect(1,token,16),'STALE_OFFER'); eq(q:view(1,16).state,'None')
        eq(q:view(2,16).state,'Invited'); eq(q:start('first',16).state,'Waiting')
        q:reply(2,q:view(2,16).offerId,false,17)
        eq(q:start('first',17).state,'NPC'); eq(q:view(1,17).state,'None')
    end)

    test('switching an invited boss invalidates the old token and fills both waiting slots',function()
        local q=queue()
        q:select(1,'Guardian',0); q:select(2,'Guardian',0)
        q:register('first','Guardian',{},0); q:register('other','Dragon',{},0)
        local old=offer(q,1)
        eq(q:select(1,'Dragon',1),'OK')
        eq(q:view(2,1).slotId,'first'); eq(q:view(1,1).slotId,'other')
        local current=q:view(1,1).offerId; assert(current~=old)
        eq(q:reply(1,old,true,1),'STALE_OFFER'); eq(q:connect(1,old,1),'STALE_OFFER')
        eq(q:view(1,1).offerId,current)
    end)

    test('cancel invalidates an invitation without changing another candidates offer',function()
        local q=queue()
        q:select(1,'Guardian',0); q:select(2,'Guardian',0); q:register('first','Guardian',{},0)
        local old=offer(q,1)
        eq(q:cancel(1,1),'OK'); eq(q:view(1,1).state,'None')
        local current=q:view(2,1).offerId
        eq(q:reply(1,old,true,2),'STALE_OFFER'); eq(q:connect(1,old,2),'STALE_OFFER')
        eq(q:view(2,2).offerId,current); eq(q:cancel(1,2),'OK')
    end)

    test('accepted and ready reserves can cancel but cannot switch bosses',function()
        local q=queue()
        q:select(1,'Guardian',0); q:select(2,'Guardian',0); q:register('first','Guardian',{},0)
        local token=offer(q,1); q:reply(1,token,true,1)
        eq(q:select(1,'Dragon',2),'ROLE_RESERVED'); eq(q:view(1,2).state,'Accepted')
        eq(q:connect(1,token,2),'OK'); eq(q:select(1,'Dragon',2),'ROLE_RESERVED')
        eq(q:cancel(1,2),'OK'); eq(q:view(1,2).state,'None'); eq(q:view(2,2).state,'Invited')
        eq(q:connect(1,token,2),'STALE_OFFER')
    end)

    -- The user's shared assignment must exclude them from every other open slot.
    test('simultaneous slots offer distinct users in registration order',function()
        local q=queue()
        q:register('z-first','Guardian',{},0); q:register('a-second','Guardian',{},0)
        q:select(1,'Guardian',0); q:select(2,'Guardian',0)
        eq(q:view(1,0).slotId,'z-first'); eq(q:view(2,0).slotId,'a-second')
        local token=offer(q,1); q:reply(1,token,true,1)
        q:register('third','Guardian',{},1); eq(q:start('third',1).state,'NPC')
        q:connect(1,token,2); eq(q:start('z-first',2).state,'Human')
        eq(q:select(1,'Dragon',2),'ROLE_RESERVED'); eq(q:cancel(1,2),'ROLE_ACTIVE')
        eq(q:view(1,2).slotId,'z-first')
    end)

    test('signed Studio user identities preserve FIFO and exclusive ownership',function()
        local q=queue()
        eq(q:select(-1,'Guardian',0),'OK'); eq(q:select(-2,'Guardian',0),'OK')
        eq(q:select(0,'Guardian',0),'OK'); eq(q:view(-1,0).position,1)
        q:register('first','Guardian',{},0); q:register('second','Guardian',{},0)
        eq(q:view(-1,0).slotId,'first'); eq(q:view(-2,0).slotId,'second')
        eq(q:view(0,0).state,'Queued')
        local token=offer(q,-1); eq(q:reply(-1,token,true,1),'OK')
        eq(q:connect(-1,token,1),'OK'); eq(q:start('first',1).userId,-1)
        eq(q:select(-1,'Dragon',1),'ROLE_RESERVED')
    end)

    test('eligibility excludes active ordinary roles globally and same group heroes per slot',function()
        local ordinary={[3]=true}
        local q=queue(function(userId,context)
            return not ordinary[userId] and not (context and context.heroId==userId)
        end)
        eq(q:select(3,'Guardian',0),'INELIGIBLE')
        q:select(1,'Guardian',0); q:select(2,'Guardian',0)
        q:register('same-group','Guardian',{heroId=1},0)
        eq(q:view(1,0).state,'Queued'); eq(q:view(2,0).slotId,'same-group')
        q:register('different-group','Guardian',{heroId=99},0)
        eq(q:view(1,0).slotId,'different-group')
    end)

    test('eligibility change clears an unresolved reserve before next invitation',function()
        local blocked={}
        local q=queue(function(userId) return not blocked[userId] end)
        q:select(1,'Guardian',0); q:select(2,'Guardian',0); q:register('first','Guardian',{},0)
        local old=offer(q,1); q:reply(1,old,true,1)
        blocked[1]=true; q:step(2)
        eq(q:view(1,2).state,'None'); eq(q:view(2,2).state,'Invited')
        eq(q:connect(1,old,2),'STALE_OFFER')
    end)

    test('NPC selection cannot be replaced by later queue entries',function()
        local q=queue()
        q:register('first','Guardian',{},0); eq(q:start('first',0).state,'NPC')
        q:select(1,'Guardian',1); q:step(2)
        eq(q:start('first',2).state,'NPC'); eq(q:view(1,2).state,'Queued')
        q:register('future','Guardian',{},3); eq(q:view(1,3).slotId,'future')
    end)

    test('close clears the assignment without requeue and keeps later users waiting',function()
        for _,state in ipairs({'Invited','Accepted','Ready','Active'}) do
            local q=queue()
            q:select(1,'Guardian',0); q:select(2,'Guardian',0); q:register('first','Guardian',{},0)
            local old=offer(q,1)
            if state~='Invited' then q:reply(1,old,true,1) end
            if state=='Ready' or state=='Active' then q:connect(1,old,1) end
            if state=='Active' then q:start('first',1) end
            eq(q:close('first',2),'OK'); eq(q:view(1,2).state,'None'); eq(q:view(2,2).state,'Queued')
            eq(q:reply(1,old,true,2),'STALE_OFFER'); eq(q:connect(1,old,2),'STALE_OFFER')
            q:register('future','Guardian',{},2); eq(q:view(2,2).slotId,'future')
        end
    end)

    test('close at assignment expiry removes its owner without consuming the next candidate',function()
        for _,state in ipairs({'Invited','Accepted'}) do
            local q=queue()
            q:select(1,'Guardian',0); q:select(2,'Guardian',0); q:register('first','Guardian',{},0)
            local token=offer(q,1); local deadline=10
            if state=='Accepted' then q:reply(1,token,true,1); deadline=16 end
            eq(q:close('first',deadline),'OK')
            eq(q:view(1,deadline).state,'None'); eq(q:view(2,deadline).state,'Queued')
            q:register('future','Guardian',{},deadline)
            eq(q:view(2,deadline).slotId,'future')
        end
    end)

    test('stale server timestamps cannot reopen an expired invitation',function()
        local q=queue()
        q:select(1,'Guardian',0); q:register('first','Guardian',{},0)
        local old=offer(q,1); q:step(10)
        eq(q:reply(1,old,true,9),'STALE_OFFER')
        eq(q:connect(1,old,9),'STALE_OFFER'); eq(q:start('first',9).state,'NPC')
    end)

    test('private views cannot mutate queue order or the active assignment',function()
        local q=queue()
        q:select(1,'Guardian',0); q:select(2,'Guardian',0); q:register('first','Guardian',{},0)
        local view=q:view(1,0); local token=view.offerId
        view.state='Ready'; view.offerId='forged'; view.slotId='forged'; view.position=99
        eq(q:view(1,0).state,'Invited'); eq(q:view(1,0).offerId,token); eq(q:view(2,0).position,2)
        q:reply(1,token,true,1); q:connect(1,token,1)
        local started=q:start('first',1); started.userId=2
        eq(q:start('first',1).userId,1)
    end)

    test('invalid operations return errors without consuming another players invitation',function()
        local q=queue()
        eq(q:select(1.5,'Guardian',0),'INVALID_USER'); eq(q:select('1','Guardian',0),'INVALID_USER')
        eq(q:select(0/0,'Guardian',0),'INVALID_USER'); eq(q:select(1,'',0),'INVALID_BOSS')
        eq(q:select(1,'Guardian',0/0),'INVALID_TIME')
        q:select(1,'Guardian',0); q:register('first','Guardian',{},0)
        local token=offer(q,1)
        eq(q:register('first','Guardian',{},0),'SLOT_EXISTS')
        eq(q:reply(2,token,true,0),'STALE_OFFER'); eq(q:connect(2,token,0),'STALE_OFFER')
        eq(q:reply(1,token,'yes',0),'INVALID_REPLY'); eq(q:connect(1,token,0),'STALE_OFFER')
        eq(q:view(1,0).offerId,token); eq(q:close('missing',0),'UNKNOWN_SLOT')
    end)

    print('BossQueue: '..passed..' passed')
end
